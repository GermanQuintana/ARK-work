import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);
const arg=name=>{const i=args.indexOf(name);if(i<0||!args[i+1])throw new Error('Missing '+name);return args[i+1];};
const url=new URL(arg('--url'));
if(url.protocol!=='https:'||url.pathname!=='/'||url.username||url.password||url.search||url.hash)throw new Error('Use the deployed HTTPS origin');
const appId=arg('--app-id');
if(!/^plugin_asdk_app[_-][A-Za-z0-9_-]+$/.test(appId))throw new Error('Use the technical plugin_asdk_app... ID shown by ChatGPT');
const json=(path,data)=>writeFileSync(resolve(root,path),JSON.stringify(data,null,2)+'\n');
const manifest=JSON.parse(readFileSync(resolve(root,'plugin/plugin.template.json'),'utf8'));
manifest.extensions['com.openai'].interface.websiteURL=url.origin;
json('plugin/plugin.json',manifest);
json('plugin/.app.json',{apps:{'ark-work':{id:appId,required:true}}});
json('plugin/mcp.json',{$schema:'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json',mcpServers:{'ark-work':{type:'streamable-http',url:new URL('/mcp',url).href,extensions:{'com.openai':{auth:{type:'oauth',client:{mode:'dcr'},baseScopes:['ark:read','ark:write']}}}}}});
mkdirSync(resolve(root,'.agents/plugins'),{recursive:true});
json('.agents/plugins/marketplace.json',{name:'ark-work',interface:{displayName:'ARK Work'},plugins:[{name:'ark-work',source:{source:'local',path:'./plugin'},policy:{installation:'AVAILABLE',authentication:'ON_INSTALL'},category:'Productivity'}]});
console.log('Plugin linked to the deployed endpoint and registered ChatGPT connection. Commit the generated public manifests, then test installation in ChatGPT Work.');
